// playwright-cli --session NAME run-code --filename scripts/phase4_browser_check.js
// Authenticated disposable LOCAL adapter only. Creates and retains generated fixtures.
async (page) => {
  const origin = new URL(page.url()).origin
  if (!['127.0.0.1', 'localhost', '[::1]'].includes(new URL(origin).hostname)) throw new Error('Loopback fixture required')
  const diagnostics = await page.request.get(`${origin}/api/v1/diagnostics`)
  if (!diagnostics.ok() || (await diagnostics.json()).adapter !== 'local') throw new Error('Disposable local adapter required')
  const passed = [], assert = (condition, message) => { if (!condition) throw new Error(message) }
  const list = async parent => { const response = await page.request.get(`${origin}/api/v1/nodes?parent_id=${parent}&limit=50000`); assert(response.ok(), 'List request failed'); return (await response.json()).items }
  const menu = async (name, action) => { await page.getByRole('button', { name: `Actions for ${name}`, exact: true }).click(); await page.getByRole('menuitem', { name: action, exact: true }).click() }
  const create = async name => { await page.locator('.new-folder-button').click(); await page.getByLabel('Folder name', { exact: true }).fill(name); await page.getByRole('button', { name: 'Create folder', exact: true }).click(); await page.getByRole('dialog').waitFor({ state: 'hidden' }); await page.getByRole('button', { name, exact: true }).waitFor() }
  const token = Date.now(), root = `UX acceptance ${token}`, note = `UX note ${token}.txt`, noteCopy = `UX note ${token} copy.txt`
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('complementary', { name: 'Main navigation' }).getByRole('button', { name: 'My drive', exact: true }).click()
  await create(root)
  await page.getByRole('button', { name: root, exact: true }).click()
  await page.getByRole('heading', { name: root, exact: true }).waitFor()
  await create('Source'); await create('Destination')
  const folder = (await list('')).find(node => node.name === root)
  assert(folder, 'Created folder missing')
  passed.push('folder creation and navigation')

  await menu('Source', 'Rename')
  await page.getByLabel('Rename Source', { exact: true }).fill('Source renamed')
  await page.getByRole('button', { name: 'Save name', exact: true }).click()
  await page.getByRole('button', { name: 'Source renamed', exact: true }).waitFor()
  await menu('Source renamed', 'Rename')
  await page.getByLabel('Rename Source renamed', { exact: true }).fill('Destination')
  await page.getByRole('button', { name: 'Save name', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: /already|exist|conflict/i }).waitFor()
  assert((await list(folder.id)).some(node => node.name === 'Source renamed'), 'Rejected rename lost original name')
  await page.getByRole('button', { name: 'Cancel rename', exact: true }).click()
  if (await page.getByRole('button', { name: 'Dismiss file action error', exact: true }).count()) await page.getByRole('button', { name: 'Dismiss file action error', exact: true }).click()
  passed.push('inline rename and collision rollback')

  await page.getByRole('button', { name: 'Grid view', exact: true }).click()
  await page.getByRole('button', { name: 'Source renamed', exact: true }).click()
  assert(await page.getByRole('button', { name: 'List view', exact: true }).getAttribute('aria-pressed') === 'true', 'New folder inherited wrong view')
  await page.getByRole('navigation', { name: 'Folder breadcrumb' }).getByRole('button', { name: root, exact: true }).click()
  assert(await page.getByRole('button', { name: 'Grid view', exact: true }).getAttribute('aria-pressed') === 'true', 'Folder view preference lost')
  await page.getByRole('button', { name: 'List view', exact: true }).click()
  await page.getByRole('columnheader', { name: 'File size', exact: true }).click()
  assert(await page.getByRole('columnheader', { name: 'File size', exact: true }).getAttribute('aria-sort') === 'ascending', 'Sort state missing')
  passed.push('per-folder view preferences and sortable headers')

  await page.getByLabel('Choose files to upload', { exact: true }).setInputFiles([{ name: note, mimeType: 'text/plain', buffer: Buffer.from('Harbor Phase 4 browser fixture.\nEncrypted roundtrip.\n') }])
  await page.getByRole('heading', { name: 'All transfers complete', exact: true }).waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: 'Close transfer queue', exact: true }).click()
  await menu(note, 'Copy')
  await page.getByRole('button', { name: 'Paste here', exact: true }).click()
  await page.getByRole('heading', { name: 'All transfers complete', exact: true }).waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: 'Close transfer queue', exact: true }).click()
  await page.getByRole('button', { name: noteCopy, exact: true }).waitFor()
  const notes = (await list(folder.id)).filter(node => [note, noteCopy].includes(node.name))
  assert(notes.length === 2 && notes[0].sha256 === notes[1].sha256, 'Copy SHA-256 mismatch')
  await menu(noteCopy, 'Cut')
  await menu('Destination', 'Paste into folder')
  await page.getByRole('status').filter({ hasText: 'Moved to new folder' }).waitFor()
  const destination = (await list(folder.id)).find(node => node.name === 'Destination')
  assert((await list(destination.id)).some(node => node.name === noteCopy), 'Cut/paste did not move')
  passed.push('browser upload, bounded copy checksum, cut/paste')

  await menu('Source renamed', 'Copy')
  await page.getByRole('button', { name: 'Paste here', exact: true }).click()
  await page.getByRole('button', { name: 'Source renamed copy', exact: true }).waitFor()
  await page.getByRole('heading', { name: 'All transfers complete', exact: true }).waitFor({ timeout: 30000 })
  await page.getByRole('button', { name: 'Close transfer queue', exact: true }).click()
  await page.getByRole('button', { name: 'Clear clipboard', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Select Source renamed', exact: true }).check()
  await page.getByRole('button', { name: 'Destination', exact: true }).click({ modifiers: ['Meta'] })
  await page.getByRole('toolbar', { name: 'Selected file actions' }).getByText('2 selected', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await menu(note, 'Add to favorites')
  await page.getByRole('navigation').getByRole('button', { name: 'Favorites', exact: true }).click()
  await page.getByRole('button', { name: note, exact: true }).waitFor()
  await menu(note, 'Move to trash')
  await page.getByRole('navigation').getByRole('button', { name: 'Trash', exact: true }).click()
  await page.getByRole('button', { name: note, exact: true }).waitFor()
  await menu(note, 'Restore')
  await page.getByRole('navigation').getByRole('button', { name: 'Favorites', exact: true }).click()
  await page.getByRole('button', { name: note, exact: true }).waitFor()
  passed.push('folder copy, modifier selection, favorites, trash and restore')

  await page.getByRole('button', { name: 'Open command palette (⌘ K / Ctrl K)', exact: true }).click()
  await page.getByRole('combobox', { name: 'Search actions or files' }).fill(note)
  await page.getByRole('combobox', { name: 'Search actions or files' }).press('Enter')
  await page.getByRole('dialog', { name: note, exact: true }).waitFor()
  assert(await page.getByLabel('Text preview', { exact: true }).textContent() === 'Harbor Phase 4 browser fixture.\nEncrypted roundtrip.\n', 'Text preview mismatch')
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await page.keyboard.press('/')
  assert(await page.getByRole('searchbox', { name: 'Search your drive' }).evaluate(node => document.activeElement === node), 'Search shortcut failed')
  await page.getByRole('searchbox', { name: 'Search your drive' }).fill(note)
  await page.getByRole('button', { name: note, exact: true }).waitFor()
  await page.getByRole('searchbox', { name: 'Search your drive' }).fill('')
  passed.push('command palette, exact text preview, search shortcut')
  return { result: 'PASS', passed, fixture: root, folder_id: folder.id }
}

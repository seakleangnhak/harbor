// playwright-cli --session NAME run-code --filename scripts/phase4_mobile_check.js
// Authenticated disposable local adapter, generated Design library fixtures only.
async (page) => {
  const diagnostics = await page.request.get(new URL('/api/v1/diagnostics', page.url()).href)
  if (!diagnostics.ok() || (await diagnostics.json()).adapter !== 'local') throw new Error('Disposable local adapter required')
  const assert = (condition, message) => { if (!condition) throw new Error(message) }, passed = []
  await page.setViewportSize({ width: 390, height: 844 }); await page.reload()
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Main navigation', exact: true })
  await drawer.waitFor()
  await page.getByRole('button', { name: 'Close navigation', exact: true }).focus()
  await page.keyboard.press('Shift+Tab')
  assert(await drawer.evaluate(element => element.contains(document.activeElement)), 'Drawer reverse focus escaped')
  await page.keyboard.press('Tab')
  assert(await page.getByRole('button', { name: 'Close navigation', exact: true }).evaluate(element => element === document.activeElement), 'Drawer forward focus failed')
  await page.screenshot({ path: 'docs/screenshots/after-mobile-navigation.png', animations: 'disabled' })
  await drawer.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('dialog', { name: 'Your private workspace', exact: true }).waitFor()
  assert(await page.getByRole('dialog', { name: 'Main navigation', exact: true }).count() === 0, 'Drawer remained open behind settings')
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  passed.push('mobile drawer focus trap and settings handoff')

  await page.getByRole('button', { name: 'Design library', exact: true }).click()
  await page.getByRole('button', { name: 'List view', exact: true }).click()
  const row = page.getByRole('row', { name: 'Projects, folder', exact: true })
  await row.evaluate(async element => {
    const init = { pointerType: 'touch', pointerId: 1, clientX: 90, clientY: 300, button: 0, bubbles: true }
    element.dispatchEvent(new PointerEvent('pointerdown', init))
    await new Promise(resolve => setTimeout(resolve, 480))
    element.dispatchEvent(new PointerEvent('pointerup', init))
  })
  await page.getByRole('toolbar', { name: 'Selected file actions', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await page.getByRole('button', { name: 'Actions for Projects', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).click()
  await page.getByLabel('Rename Projects', { exact: true }).waitFor()
  await page.screenshot({ path: 'docs/screenshots/after-mobile-rename.png', animations: 'disabled' })
  const save = await page.getByRole('button', { name: 'Save name', exact: true }).boundingBox()
  const input = await page.getByLabel('Rename Projects', { exact: true }).boundingBox()
  assert(save.width >= 44 && save.height >= 44 && input.width >= 100, 'Mobile rename targets cramped')
  await page.getByRole('button', { name: 'Cancel rename', exact: true }).click()
  await page.getByRole('button', { name: 'Actions for Projects', exact: true }).click()
  await page.screenshot({ path: 'docs/screenshots/after-mobile-menu.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  passed.push('touch long press, mobile context actions, usable inline rename')

  await page.getByRole('button', { name: 'Coastline.png', exact: true }).click()
  await page.locator('img.image-canvas').evaluate(image => image.decode())
  const preview = await page.getByRole('dialog', { name: 'Coastline.png', exact: true }).boundingBox()
  assert(preview.width <= 390 && preview.height <= 844 && preview.x >= 0 && preview.y >= 0, 'Mobile preview clipped')
  await page.screenshot({ path: 'docs/screenshots/after-mobile-preview.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Transfer queue', exact: true }).click()
  const transfer = await page.getByRole('region', { name: 'Transfer queue', exact: true }).boundingBox()
  assert(transfer.width <= 390 && transfer.x >= 0 && transfer.y >= 0, 'Mobile transfers clipped')
  await page.screenshot({ path: 'docs/screenshots/after-mobile-transfers.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Close transfer queue', exact: true }).click()
  assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Mobile horizontal overflow')
  passed.push('fullscreen mobile preview, transfer panel, no page overflow')
  return { result: 'PASS', passed, viewport: '390x844', rename_input_width: input.width, rename_target: [save.width, save.height] }
}
